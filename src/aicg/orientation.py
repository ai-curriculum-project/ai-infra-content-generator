"""Per-role orientation module: "Your Relationship to the Model".

Every role in the org family gets the same opening module, rendered for
that role: which verb its org performs against the model, what it owns, what it
hands each sibling org (and gets back), the nearest-level counterpart role in
each sibling org, its own ladder neighbours, and a shared scenario (one model
upgrade) with the role's part highlighted.

Facts (roles, levels, repos) come from the manifests; editorial content comes
from ``config/stances.json``. The module lives at
``<container>/00-your-relationship-to-the-model/`` -- deliberately *not*
``mod-NNN`` -- so the plan/pairing/nav audits don't treat it as a planned
module that needs a solutions pair. ``CURRICULUM.md`` links it through a
marker-delimited "Start here" block.

Rendering is pure; only ``load_stances`` and ``write_orientation`` touch disk.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from .domain_provision import _org_display

ORIENTATION_SLUG = "00-your-relationship-to-the-model"
EXERCISE_PATH = "exercises/exercise-01-map-your-model-boundary.md"
BLOCK_START = "<!-- aicg:orientation:start -->"
BLOCK_END = "<!-- aicg:orientation:end -->"
GENERATED_NOTE = (
    "<!-- Generated by `aicg org render-orientation` from config/stances.json and the "
    "org manifests. Edit those, not this file. -->"
)
DOMAIN_KEYS = ("verb", "headline", "stance", "owns", "not_owns", "hands_to")


class StanceError(ValueError):
    """Raised when stances.json is malformed or incomplete."""


# --- stances ---------------------------------------------------------------------


def load_stances(path: Path) -> dict[str, Any]:
    """Load ``stances.json`` and check every domain/handoff/step is present."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    domains = data.get("domains") or {}
    names = set(domains)
    if set(data.get("order") or []) != names:
        raise StanceError(f"'order' must list exactly the domains {sorted(names)}")
    for name, stance in domains.items():
        missing = [k for k in DOMAIN_KEYS if not stance.get(k)]
        if missing:
            raise StanceError(f"domain {name!r} missing key(s) {missing}")
        absent = sorted(names - {name} - set(stance["hands_to"]))
        if absent:
            raise StanceError(f"domain {name!r} has no hands_to entry for {absent}")
        unknown = sorted(set(stance.get("counterpart_for") or {}) - names)
        if unknown:
            raise StanceError(f"domain {name!r} counterpart_for names unknown domain(s) {unknown}")
    steps = (data.get("scenario") or {}).get("steps") or {}
    absent_steps = sorted(names - set(steps))
    if absent_steps:
        raise StanceError(f"scenario.steps missing domain(s) {absent_steps}")
    return data


# --- helpers ---------------------------------------------------------------------


def _org_name(manifest: Any) -> str:
    return _org_display(manifest.org)


def _link(manifest: Any, role: Any) -> str:
    return f"[{role.title}](https://github.com/{manifest.org}/{role.learning_repo})"


def _find_role(manifest: Any, role_id: str) -> Any:
    for role in manifest.roles:
        if role.id == role_id:
            return role
    raise KeyError(f"role {role_id!r} not in {manifest.org}")


def _nearest(manifest: Any, level: int) -> Any:
    """Closest-level role; ties go to the lower level, then title."""
    return min(manifest.roles, key=lambda r: (abs(r.level - level), r.level, r.title))


def _counterpart(
    domain: str, role: Any, other: str, manifest: Any, stances: Mapping[str, Any]
) -> Any:
    """Pick the sibling-org role this role most likely works with.

    Levels only compare across seniority ladders. If the sibling uses path-order
    levels, use its declared counterpart for our domain; if we do, pair with the
    sibling's most senior role (the leader a founder works with).
    """
    theirs = stances["domains"][other]
    if theirs.get("path_levels"):
        wanted = (theirs.get("counterpart_for") or {}).get(domain)
        if wanted:
            return _find_role(manifest, wanted)
    if stances["domains"][domain].get("path_levels"):
        return max(manifest.roles, key=lambda r: (r.level, r.title))
    return _nearest(manifest, role.level)


def _ladder(manifest: Any, role: Any) -> tuple[list[Any], list[Any], list[Any]]:
    """(rung below, peers at the same level, rung above)."""
    others = [r for r in manifest.roles if r.id != role.id]
    below = [r for r in others if r.level < role.level]
    above = [r for r in others if r.level > role.level]
    peers = sorted((r for r in others if r.level == role.level), key=lambda r: r.title)
    top_below = max((r.level for r in below), default=None)
    low_above = min((r.level for r in above), default=None)
    return (
        sorted((r for r in below if r.level == top_below), key=lambda r: r.title),
        peers,
        sorted((r for r in above if r.level == low_above), key=lambda r: r.title),
    )


def _count_word(n: int) -> str:
    words = {3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine"}
    return words.get(n, str(n))


def _join(manifest: Any, roles: list[Any]) -> str:
    return ", ".join(_link(manifest, r) for r in roles)


# --- sections --------------------------------------------------------------------


def _intro(role: Any, org: str, stance: Mapping[str, Any]) -> list[str]:
    return [
        "# Module 00: Your Relationship to the Model\n",
        GENERATED_NOTE + "\n",
        f"> **Role:** {role.title} · **Org:** {org} Curriculum · **Level:** L{role.level}\n",
        "Every role in the AI Career Curriculum works on the same thing, a model, from a "
        "different side. Before the technical modules, this one tells you which side is "
        "yours, what you own there, and who you depend on.\n",
        "## Where you stand\n",
        f"{stance['headline']}\n",
        f"{stance['stance']}\n",
    ]


def _family_table(domain: str, family: Mapping[str, Any], stances: Mapping[str, Any]) -> list[str]:
    out = [
        f"## The {_count_word(len(stances['order']))} relationships\n",
        "| Org | Relationship to the model |",
        "|-----|---------------------------|",
    ]
    for name in stances["order"]:
        manifest = family.get(name)
        if manifest is None:
            continue
        label = f"[{_org_name(manifest)}](https://github.com/{manifest.org})"
        here = " *(you are here)*" if name == domain else ""
        out.append(f"| {label}{here} | {stances['domains'][name]['headline']} |")
    return out + [""]


def _ownership(stance: Mapping[str, Any]) -> list[str]:
    out = ["## What you own\n"]
    out += [f"- {item}" for item in stance["owns"]]
    return out + ["", f"**What you don't own:** {stance['not_owns']}\n"]


def _handoffs(
    domain: str, role: Any, family: Mapping[str, Any], stances: Mapping[str, Any]
) -> list[str]:
    out = [
        "## Who you work with\n",
        "Each row is a sibling org: what you hand them, what they hand you, and the role "
        "there closest to your level, the person you're most likely to work with.\n",
        "| Org | You hand them | They hand you | Your nearest counterpart |",
        "|-----|---------------|---------------|--------------------------|",
    ]
    mine = stances["domains"][domain]["hands_to"]
    for name in stances["order"]:
        manifest = family.get(name)
        if name == domain or manifest is None or not manifest.roles:
            continue
        theirs = stances["domains"][name]["hands_to"][domain]
        counterpart = _link(manifest, _counterpart(domain, role, name, manifest, stances))
        out.append(f"| {_org_name(manifest)} | {mine[name]} | {theirs} | {counterpart} |")
    return out + [""]


def _ladder_section(manifest: Any, role: Any) -> list[str]:
    below, peers, above = _ladder(manifest, role)
    out = ["## Your ladder\n"]
    out.append(
        f"- **Before this role:** {_join(manifest, below)}"
        if below
        else "- **Before this role:** this is the entry point of the ladder."
    )
    if peers:
        out.append(f"- **Alongside it (same level):** {_join(manifest, peers)}")
    out.append(
        f"- **After this role:** {_join(manifest, above)}"
        if above
        else "- **After this role:** this is the top of this ladder. Growth from here "
        "usually means moving across to a sibling org's senior roles."
    )
    return out + [""]


def _scenario(domain: str, family: Mapping[str, Any], stances: Mapping[str, Any]) -> list[str]:
    scenario = stances["scenario"]
    out = [f"## Scenario: {scenario['title']}\n", f"{scenario['intro']}\n"]
    for i, name in enumerate(stances["order"], start=1):
        manifest = family.get(name)
        org = _org_name(manifest) if manifest is not None else name
        step = scenario["steps"][name]
        text = f"**{step}** ← your part" if name == domain else step
        out.append(f"{i}. **{org}:** {text}")
    return out + ["", f"{scenario['close']}\n"]


def _next_steps() -> list[str]:
    return [
        "## Before you move on\n",
        f"Do [Exercise 01: Map your model boundary]({EXERCISE_PATH}). Then start the first "
        "technical module in [CURRICULUM.md](../../CURRICULUM.md).\n",
    ]


def _exercise(role: Any, domain: str, stances: Mapping[str, Any]) -> str:
    verb = stances["domains"][domain]["verb"]
    return "\n".join(
        [
            "# Exercise 01: Map Your Model Boundary\n",
            GENERATED_NOTE + "\n",
            f"**Role:** {role.title} · **Time:** 45–60 minutes · **Output:** one diagram and "
            "one page of notes\n",
            "## Goal\n",
            f"Make your relationship to the model concrete. As a {role.title}, you **{verb}** "
            "the model. Draw where that work starts and stops in a real system.\n",
            "## Steps\n",
            "1. **Pick a system.** Choose one AI system you've worked on, use, or can read "
            "about in detail (an open-source project, a vendor case study, or your "
            "employer's product).",
            "2. **Draw it.** Sketch the model in the middle, then the layers around it: data "
            "and training, serving infrastructure, the application or agent, policy and "
            "oversight, and the business that pays for it.",
            "3. **Mark your boundary.** Shade what someone in your role would own. Use the "
            "\"What you own\" list in the module README as a starting point and adjust it to "
            "the real system.",
            "4. **Label every handoff.** For each arrow that crosses your boundary, write what "
            "crosses it (an artifact, a metric, a requirement, a decision) and which role is "
            "on the other side.",
            "5. **Find one failure.** Describe one realistic incident that starts outside your "
            "boundary and lands inside it, or the reverse. Who notices first? What would you "
            "need from the other side to fix it?",
            "6. **Write three questions.** List three questions you'd ask your nearest "
            "counterpart in a sibling org in your first week on the job.\n",
            "## What good looks like\n",
            "- Every arrow crossing your boundary names a concrete thing, not \"collaboration\".",
            "- The failure scenario involves at least two orgs and is specific enough to "
            "write a postmortem about.",
            "- Your questions would get a useful answer from a busy colleague in under five "
            "minutes.\n",
            "## Keep it\n",
            "Save the diagram. You'll revisit it at the end of the curriculum: it should have "
            "more detail, and some of your boundary lines will have moved.\n",
        ]
    )


# --- public API ------------------------------------------------------------------


def render_orientation(
    role_id: str, domain: str, family: Mapping[str, Any], stances: Mapping[str, Any]
) -> dict[str, str]:
    """Render the orientation files for one role, keyed by path within the module dir."""
    manifest = family[domain]
    role = _find_role(manifest, role_id)
    stance = stances["domains"][domain]
    sections = (
        _intro(role, _org_name(manifest), stance)
        + _family_table(domain, family, stances)
        + _ownership(stance)
        + _handoffs(domain, role, family, stances)
        + _ladder_section(manifest, role)
        + _scenario(domain, family, stances)
        + _next_steps()
    )
    return {
        "README.md": "\n".join(sections).rstrip() + "\n",
        EXERCISE_PATH: _exercise(role, domain, stances).rstrip() + "\n",
    }


def _block(container: str) -> str:
    return (
        f"{BLOCK_START}\n"
        f"> **Start here:** [Module 00: Your Relationship to the Model]"
        f"({container}/{ORIENTATION_SLUG}/README.md). Where this role sits relative to the "
        "model, what it owns, and who it works with across the sibling curricula.\n"
        f"{BLOCK_END}"
    )


def upsert_curriculum_block(text: str, container: str = "lessons") -> str:
    """Insert (or refresh) the 'Start here' block right after the H1."""
    block = _block(container)
    start, end = text.find(BLOCK_START), text.find(BLOCK_END)
    if start != -1 and end != -1:
        return text[:start] + block + text[end + len(BLOCK_END):]
    lines = text.split("\n")
    if lines and lines[0].startswith("# "):
        rest = "\n".join(lines[1:]).lstrip("\n")
        return f"{lines[0]}\n\n{block}\n\n{rest}"
    return f"{block}\n\n{text}"


def _container(repo: Path) -> str:
    if (repo / "modules").is_dir() and not (repo / "lessons").is_dir():
        return "modules"
    return "lessons"


def write_orientation(
    workspace: Path,
    role_id: str,
    domain: str,
    family: Mapping[str, Any],
    stances: Mapping[str, Any],
) -> list[Path]:
    """Write the module into the role's learning repo. Returns paths written."""
    role = _find_role(family[domain], role_id)
    repo = Path(workspace) / role.learning_repo
    if not repo.is_dir():
        return []
    container = _container(repo)
    base = repo / container / ORIENTATION_SLUG
    written: list[Path] = []
    for rel, content in render_orientation(role_id, domain, family, stances).items():
        path = base / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    curriculum = repo / "CURRICULUM.md"
    if curriculum.exists():
        text = curriculum.read_text(encoding="utf-8")
        updated = upsert_curriculum_block(text, container)
        if updated != text:
            curriculum.write_text(updated, encoding="utf-8")
        written.append(curriculum)
    return written
